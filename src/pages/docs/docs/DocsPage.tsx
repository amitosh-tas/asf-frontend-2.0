const NO_NPM_TRACK = `<script>
(function () {
  var API_BASE_URL = "YOUR_ATTRIBUTION_API_URL";
  var PUBLISHABLE_KEY = "pk_test_YOUR_PUBLISHABLE_KEY";

  function visitorId() {
    var id = localStorage.getItem("elysium_visitor_id");
    if (!id) {
      id = crypto.randomUUID();
      localStorage.setItem("elysium_visitor_id", id);
    }
    return id;
  }

  var query = new URLSearchParams(window.location.search);
  fetch(API_BASE_URL.replace(/\\/$/, "") + "/v1/touches", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "X-Api-Key": PUBLISHABLE_KEY,
      "Authorization": "Bearer " + PUBLISHABLE_KEY
    },
    body: JSON.stringify({
      visitorId: visitorId(),
      touchedAt: new Date().toISOString(),
      source: query.get("utm_source"),
      medium: query.get("utm_medium"),
      campaign: query.get("utm_campaign"),
      term: query.get("utm_term"),
      content: query.get("utm_content"),
      referrer: document.referrer || null,
      landingPage: window.location.href,
      pageTitle: document.title,
      gclid: query.get("gclid"),
      fbclid: query.get("fbclid"),
      ttclid: query.get("ttclid"),
      msclkid: query.get("msclkid")
    })
  }).then(function (response) {
    if (!response.ok) console.error("Elysium tracking failed", response.status);
  }).catch(function (error) {
    console.error("Elysium tracking could not reach the API", error);
  });
})();
</script>`;

