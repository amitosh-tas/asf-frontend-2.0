export const NON_NPM_SNIPPET = `<script>
(function () {
  // Replace with your API base URL and your PUBLISHABLE key (pk_live_... / pk_test_...).
  var API_BASE_URL = "https://api.yourdomain.com";
  var PUBLISHABLE_KEY = "pk_live_YOUR_PUBLISHABLE_KEY";

  function post(path, body) {
    return fetch(API_BASE_URL + path, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "Authorization": "Bearer " + PUBLISHABLE_KEY
      },
      body: JSON.stringify(body)
    }).then(function (res) {
      if (!res.ok) throw new Error("Request failed: " + res.status);
      return res.json();
    });
  }

  // A stable anonymous ID, generated once and kept in localStorage.
  function getVisitorId() {
    try {
      var id = localStorage.getItem("elysium_visitor_id");
      if (!id) {
        id = crypto.randomUUID();
        localStorage.setItem("elysium_visitor_id", id);
      }
      return id;
    } catch (e) {
      return null; // storage blocked: skip tracking rather than guess an ID
    }
  }

  var visitorId = getVisitorId();
  if (!visitorId) return;

  // 1. Record a touch on every page view.
  var q = new URLSearchParams(window.location.search);
  post("/v1/touches", {
    visitorId: visitorId,
    touchedAt: new Date().toISOString(),
    source: q.get("utm_source"),
    medium: q.get("utm_medium"),
    campaign: q.get("utm_campaign"),
    term: q.get("utm_term"),
    content: q.get("utm_content"),
    referrer: document.referrer || null,
    landingPage: window.location.href,
    pageTitle: document.title,
    gclid: q.get("gclid"),
    fbclid: q.get("fbclid"),
    ttclid: q.get("ttclid"),
    msclkid: q.get("msclkid")
  }).catch(function () {});

  // 2. Expose helpers for forms and checkout.
  window.ElysiumDirect = {
    identify: function (email, phone) {
      return post("/v1/identify", { visitorId: visitorId, email: email, phone: phone });
    },
    createCheckoutSession: function () {
      return post("/v1/checkout-sessions", { visitorId: visitorId, expiresInMs: 7200000 });
    }
  };
})();
</script>`;

